# ordem correta na matematica
# parentese --> exponencial --> multiplicação/divisão(da esquerda pra direita) --> adição/subtração(da esquerda pra direita)


produto_1 = 20
produto_2 = 10

print(produto_1 + produto_2) # soma
print(produto_1 - produto_2) # subtração
print(produto_1 / produto_2) # divisão resultado float
print(produto_1 // produto_2) # divisão resultado inteiro
print(produto_1 * produto_2) # multiplicação
print(produto_1 % produto_2) # modulo (resto da divisão)
print(produto_1 ** produto_2) # exponeciação

x = (10 + 5) * 4
